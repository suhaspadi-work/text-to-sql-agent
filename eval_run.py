import json
import os
import re
import time
from langgraph.types import Command
from sql_agent import agent

# Each entry: (question, expected answer for display, match rule)
# match rule is a list (ALL keywords must appear) or {"any": [...]} (at least one must appear)
EVAL_SET = [
    ("How many tracks are in the Rock genre?", "1297", ["1297"]),
    ("Which country has the most customers?", "USA (13)", ["usa", "13"]),
    ('Who is the artist for the track "Balls to the Wall"?', "Accept", ["accept"]),
    ("What is the average invoice total, rounded to 2 decimals?", "5.65", ["5.65"]),
    ("How many employees are there?", "8", ["8"]),
    ("Which playlist has the most tracks?", "Music (3290)", ["music", "3290"]),
    ("How many distinct customers have billed from the USA?", "13", ["13"]),
    ("Which media type is used by the most tracks?", "MPEG audio file", ["mpeg audio file"]),
    ("Which genre has the fewest tracks?", "Opera (1)", ["opera"]),
    ("How many customers have a support rep assigned?", "59", ["59"]),
    ("What is the total revenue generated by Jazz tracks?", "79.20", {"any": ["79.2", "79.20"]}),
    ("What is the longest track, and how long is it in milliseconds?",
     "Occupation / Precipice, 5286953 ms", ["occupation / precipice", "5286953"]),
    ("How many albums does Iron Maiden have?", "21", ["21"]),
    ("How many customers have no fax number on file?", "47", ["47"]),
    ("Which city has the most customers?",
     "Six-way tie at 2: Berlin, London, Mountain View, Paris, Prague, São Paulo",
     {"any": ["berlin", "london", "mountain view", "paris", "prague", "paulo"]}),
]

RESULTS_FILE = "eval_results.jsonl"
REPORT_FILE = "eval_results.md"
PAUSE_BETWEEN_QUESTIONS = 15   # seconds
MAX_RETRIES = 4


class ServiceUnavailable(Exception):
    """The model service is overloaded, rate-limited, or timing out. Not an agent failure."""


def extract_text(content):
    """Gemini returns a list of content blocks; flatten to plain text."""
    if isinstance(content, str):
        return content
    return " ".join(b.get("text", "") for b in content if isinstance(b, dict))


def is_transient(msg):
    markers = ("429", "500", "502", "503", "504", "RESOURCE_EXHAUSTED", "UNAVAILABLE",
               "DEADLINE_EXCEEDED", "timed out", "Timeout", "timeout")
    return any(m in msg for m in markers)


def with_retry(fn):
    """Retry transient errors with growing waits; raise ServiceUnavailable if they persist."""
    for attempt in range(MAX_RETRIES):
        try:
            return fn()
        except Exception as e:
            msg = str(e)
            if not is_transient(msg):
                raise
            if "PerDay" in msg:
                raise ServiceUnavailable("Daily quota exhausted: " + msg[:200])
            if attempt == MAX_RETRIES - 1:
                raise ServiceUnavailable("Still failing after retries: " + msg[:200])
            match = re.search(r"retry in ([\d.]+)s", msg)
            wait = int(float(match.group(1))) + 5 if match else 30 * (2 ** attempt)
            print(f"   transient error: {msg[:200]}")
            print(f"   retrying in {wait}s (attempt {attempt + 2}/{MAX_RETRIES})...")
            time.sleep(wait)


def run_question(question, thread_id):
    """Run one question. Approve only SELECT queries; reject anything else."""
    config = {"configurable": {"thread_id": thread_id}}
    queries, rejected = [], 0

    result = with_retry(lambda: agent.invoke(
        {"messages": [{"role": "user", "content": question}]}, config))

    while "__interrupt__" in result:
        request = result["__interrupt__"][0].value["action_requests"][0]
        query = str(request["args"].get("query", request["args"]))
        queries.append(query)
        if query.strip().lower().startswith("select"):
            decision = {"type": "approve"}
        else:
            decision = {"type": "reject"}
            rejected += 1
        result = with_retry(lambda: agent.invoke(
            Command(resume={"decisions": [decision]}), config))

    return extract_text(result["messages"][-1].content), queries, rejected


def keyword_hit(answer, keyword):
    """Whole-token match, ignoring case and thousands separators."""
    text = answer.lower().replace(",", "")
    return re.search(r"(?<![\w.])" + re.escape(keyword.lower()) + r"(?!\w)", text) is not None


def check(answer, rule):
    if isinstance(rule, dict):
        return any(keyword_hit(answer, k) for k in rule["any"])
    return all(keyword_hit(answer, k) for k in rule)


def load_results():
    done = {}
    if os.path.exists(RESULTS_FILE):
        with open(RESULTS_FILE) as f:
            for line in f:
                if line.strip():
                    row = json.loads(line)
                    done[row["i"]] = row
    return done


def write_report(done):
    rows = [done[i] for i in sorted(done)]
    passed = sum(1 for r in rows if r["passed"])
    with open(REPORT_FILE, "w") as f:
        f.write("# Evaluation Results\n\n")
        f.write(f"Completed {len(rows)} of {len(EVAL_SET)} questions. "
                f"Auto-check passed: {passed}/{len(rows)}. "
                "Auto-check is keyword matching; every answer was also reviewed manually.\n\n")
        f.write("| # | Question | Expected | Agent answer | Auto-check |\n|---|---|---|---|---|\n")
        for r in rows:
            clean = r["answer"].replace("\n", " ").replace("|", "/")
            f.write(f"| {r['i']} | {r['question']} | {r['expected']} | {clean} | "
                    f"{'PASS' if r['passed'] else 'REVIEW'} |\n")
        f.write("\n## SQL executed per question\n\n")
        for r in rows:
            f.write(f"**{r['i']}. {r['question']}**\n\n")
            for sql in r["queries"]:
                f.write(f"```sql\n{sql}\n```\n\n")
    return passed, len(rows)


if __name__ == "__main__":
    done = load_results()
    print(f"{len(done)} of {len(EVAL_SET)} questions already completed; resuming.")

    for i, (question, expected, rule) in enumerate(EVAL_SET, start=1):
        if i in done:
            continue
        print(f"\n[{i}/{len(EVAL_SET)}] {question}")
        try:
            answer, queries, rejected = run_question(question, thread_id=f"eval-{i}")
        except ServiceUnavailable as e:
            print(f"\nSTOPPING: model service unavailable ({e})")
            print("Nothing was recorded for this question. Re-run later to resume from here.")
            break

        passed = check(answer, rule)
        print(f"   expected: {expected}")
        print(f"   answer:   {answer[:300]}")
        print(f"   auto-check: {'PASS' if passed else 'REVIEW'}  (queries: {len(queries)}, rejected: {rejected})")

        row = {"i": i, "question": question, "expected": expected, "answer": answer,
               "passed": passed, "queries": queries, "rejected": rejected}
        with open(RESULTS_FILE, "a") as f:
            f.write(json.dumps(row) + "\n")
        done[i] = row
        time.sleep(PAUSE_BETWEEN_QUESTIONS)

    if done:
        passed, total = write_report(done)
        print(f"\nProgress: {total}/{len(EVAL_SET)} questions completed, {passed} passed auto-check.")
        print(f"Report written to {REPORT_FILE}")